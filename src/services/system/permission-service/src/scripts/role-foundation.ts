/** buildBuiltInRoleSeeds returns the complete built-in role seed set without writing to a database. */
export function buildBuiltInRoleSeeds(): BuiltInRoleSeed[] {
  return [...BUILT_IN_SYSTEM_ROLES, ...BUILT_IN_ROLE_TEMPLATES]
}

/** validateBuiltInRoleSeedDefinitions checks role seed consistency before any DB writer consumes it. */
export function validateBuiltInRoleSeedDefinitions(): string[] {
  const errors: string[] = []
  const permissionCodes = new Set(PERMISSION_CODE_SEED_ITEMS.map((item) => item.code))
  const seenRoleKeys = new Set<string>()

  for (const role of buildBuiltInRoleSeeds()) {
    const roleKey = `${role.scopeKey}:${role.kind}:${role.code}`
    if (seenRoleKeys.has(roleKey)) {
      errors.push(`Duplicate role seed key: ${roleKey}`)
    }
    seenRoleKeys.add(roleKey)

    if (role.isProtected && role.allowTenantPermissionOverride) {
      errors.push(`${role.code}: protected role cannot allow tenant permission override`)
    }

    if (role.kind === RoleKind.SYSTEM_INSTANCE) {
      if (role.scopeKey !== '__SYSTEM__') {
        errors.push(`${role.code}: SYSTEM_INSTANCE must use scopeKey __SYSTEM__`)
      }
      if (role.tenantId !== null || role.templateRoleCode !== null) {
        errors.push(`${role.code}: SYSTEM_INSTANCE must not set tenantId or templateRoleCode`)
      }
    }

    if (role.kind === RoleKind.SYSTEM_TEMPLATE) {
      if (role.scopeKey !== '__SYSTEM_TEMPLATE__') {
        errors.push(`${role.code}: SYSTEM_TEMPLATE must use scopeKey __SYSTEM_TEMPLATE__`)
      }
      if (role.tenantId !== null || role.templateRoleCode !== null) {
        errors.push(`${role.code}: SYSTEM_TEMPLATE must not set tenantId or templateRoleCode`)
      }
    }

    if (role.kind === RoleKind.TENANT_INSTANCE) {
      if (!role.tenantId) {
        errors.push(`${role.code}: TENANT_INSTANCE must set tenantId`)
      }
      if (role.tenantId && role.scopeKey !== role.tenantId) {
        errors.push(`${role.code}: TENANT_INSTANCE scopeKey must equal tenantId`)
      }
    }

    const seenPermissionCodes = new Set<string>()
    for (const permissionCode of role.permissionCodes) {
      if (seenPermissionCodes.has(permissionCode)) {
        errors.push(`${role.code}: duplicate permission code ${permissionCode}`)
      }
      seenPermissionCodes.add(permissionCode)

      if (!permissionCodes.has(permissionCode)) {
        errors.push(`${role.code}: unknown permission code ${permissionCode}`)
      }
    }
  }

  return errors
}
