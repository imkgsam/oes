import { readdirSync, readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { renderCommonPermissionCodeFiles } from '../../src/scripts/generate-common-permission-codes'

function collectRelativeFiles(rootDir: string, currentDir = rootDir): string[] {
  return readdirSync(currentDir, { withFileTypes: true }).flatMap((entry) => {
    const absolutePath = resolve(currentDir, entry.name)
    if (entry.isDirectory()) {
      return collectRelativeFiles(rootDir, absolutePath)
    }
    return [absolutePath.slice(rootDir.length + 1)]
  })
}

function parseIndexExports(content: string): string[] {
  return content
    .trim()
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith('//'))
}

function parseConstExport(content: string): {
  constName: string
  records: Record<string, string>
} {
  const sanitizedContent = content
    .trim()
    .split('\n')
    .filter((line) => !line.trim().startsWith('//'))
    .join('\n')
  const match = sanitizedContent.match(/^export const (\w+) = ([\s\S]+) as const$/)
  if (!match) {
    throw new Error(`Unable to parse const export:\n${content}`)
  }

  const [, constName, objectLiteral] = match
  // Uses trusted local source files to compare semantic export compatibility rather than formatting details.
  const records = Function(`return (${objectLiteral.trim()})`)() as Record<string, string>
  return { constName, records }
}

// Verifies the permission-service generator preserves the current common permission-code file contract.
describe('common permission code generator', () => {
  it('renders the current common permission-code files with the same paths and exports', () => {
    const commonPermissionCodesDir = resolve(
      __dirname,
      '../../../../../../src/common/src/authorization/permission-codes'
    )

    const expectedFiles = collectRelativeFiles(commonPermissionCodesDir).sort()
    const renderedFiles = renderCommonPermissionCodeFiles()
    const renderedPaths = [...renderedFiles.keys()].sort()

    expect(renderedPaths).toEqual(expectedFiles)

    for (const relativePath of expectedFiles) {
      const currentContent = readFileSync(
        resolve(commonPermissionCodesDir, relativePath),
        'utf8'
      ).trim()
      const renderedContent = renderedFiles.get(relativePath)?.trim()
      expect(renderedContent?.startsWith('// Generated by permission-service')).toBe(true)
      expect(currentContent.startsWith('// Generated by permission-service')).toBe(true)

      if (relativePath.endsWith('index.ts')) {
        expect(parseIndexExports(renderedContent ?? '')).toEqual(parseIndexExports(currentContent))
        continue
      }

      expect(parseConstExport(renderedContent ?? '')).toEqual(parseConstExport(currentContent))
    }
  })
})
